CREATE TABLE users(
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 first_name VARCHAR(80) NOT NULL,middle_name VARCHAR(80) NOT NULL,last_name VARCHAR(80) NOT NULL,
 phone VARCHAR(30) NOT NULL UNIQUE,pin_hash VARCHAR(255) NOT NULL,
 role ENUM('user','admin') NOT NULL DEFAULT 'user',coins INT NOT NULL DEFAULT 0,
 status ENUM('active','suspended') NOT NULL DEFAULT 'active',
 failed_attempts INT NOT NULL DEFAULT 0,locked_until DATETIME NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE verification_requests(
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,user_id BIGINT UNSIGNED NOT NULL,
 phone_number VARCHAR(30) NOT NULL,consent TINYINT(1) NOT NULL DEFAULT 0,
 status ENUM('pending','processing','completed','rejected') NOT NULL DEFAULT 'pending',
 result_nida_number VARCHAR(40) NULL,result_full_name VARCHAR(255) NULL,
 admin_note VARCHAR(500) NULL,processed_by BIGINT UNSIGNED NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,updated_at TIMESTAMP NULL,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY(processed_by) REFERENCES users(id) ON DELETE SET NULL,
 INDEX(status),INDEX(user_id)
) ENGINE=InnoDB;
CREATE TABLE transactions(
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,user_id BIGINT UNSIGNED NOT NULL,
 amount INT NOT NULL,type ENUM('credit','debit') NOT NULL,description VARCHAR(255) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;
CREATE TABLE activity_logs(
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,user_id BIGINT UNSIGNED NULL,
 action VARCHAR(255) NOT NULL,ip_address VARCHAR(45) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,INDEX(created_at)
) ENGINE=InnoDB;

CREATE TABLE topup_requests(
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL, amount INT NOT NULL,
 payment_method VARCHAR(40) NOT NULL, reference_code VARCHAR(100) NOT NULL, status ENUM('pending','approved','rejected') NOT NULL DEFAULT 'pending',
 admin_note VARCHAR(255) NULL, processed_by BIGINT UNSIGNED NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, processed_at DATETIME NULL,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE CASCADE, FOREIGN KEY(processed_by) REFERENCES users(id) ON DELETE SET NULL, INDEX(status), INDEX(user_id)
) ENGINE=InnoDB;
